static int same(const char *a, const char *b) { while (*a && *a == *b) { a++; b++; } return *a == *b; }

const char *tr(const char *en)
{
    if (!cur_lang || !en) return en;
    for (unsigned i = 0; i < sizeof T / sizeof T[0]; i++)
        if (same(en, T[i][0])) return T[i][1];
    return en;
}
